//! Story - Domain binding for App app instances.
//!
//! Default domain pattern: `{app}.{env}.{org_domain}` - every subdomain is
//! derived from the org's entered domain (custom or default `{slug}.{base}`).
//! The obsolete `*.app.{base_domain}` wildcard pattern has been removed.
//! Custom domains are verified via DNS TXT record challenge.
//!
//! See

use sha2::{Digest, Sha256};
use uuid::Uuid;

/// A domain binding record for an app instance.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DomainBinding {
    /// The fully-qualified domain name (default or custom).
    pub domain: String,
    /// The app instance ID this domain is bound to.
    pub instance_id: Uuid,
    /// Random verification token placed in DNS TXT record.
    pub verification_token: String,
    /// Whether the domain has been verified via DNS TXT challenge.
    pub verified: bool,
}

/// Generate the default domain for an app instance.
///
/// Pattern: `{app}.{env}.{org_domain}`
/// `org_domain` is the org's entered domain (custom or default
/// `{slug}.{base_domain}`), so every required subdomain is created from the
/// org/env domains - no platform `app.{base}` wildcard. Matches tls's
/// `derive_mappings` app pattern (`{app_slug}.{env_domain}`).
///
/// `app` is slugified (lowercase, alphanumerics + hyphens only) to keep the
/// DNS label valid; `env` and `org_domain` are taken verbatim (they are
/// already valid DNS labels from sys).
pub fn generate_default_domain(app: &str, env: &str, org_domain: &str) -> String {
    let app = slugify(app);
    let env = slugify(env);
    let org = org_domain.trim_start_matches('.');
    format!("{app}.{env}.{org}")
}

/// Generate a DNS TXT verification token for a domain.
///
/// Returns a deterministic, URL-safe token derived from the domain SHA-256
/// hash plus 16 random bytes (so re-generating yields a new challenge).
/// Prefix `sentin8-domain-verify=` is NOT included - callers place the raw
/// token as the TXT record value.
pub fn generate_dns_txt_token(domain: &str) -> String {
    let mut hasher = Sha256::new();
    hasher.update(domain.as_bytes());
    hasher.update(b"|");
    let rand_bytes: [u8; 16] = rand::random();
    hasher.update(rand_bytes);
    let digest = hasher.finalize();
    // Use the first 16 bytes (32 hex chars) - enough entropy for a challenge.
    let hex: String = digest.iter().take(16).map(|b| format!("{b:02x}")).collect();
    format!("sentin8-verify-{hex}")
}

/// Verify a DNS TXT record against the expected verification token.
///
/// The TXT record value may either be the bare token or include the
/// `sentin8-domain-verify=` prefix (common conventions). This helper accepts
/// both forms. Returns `Ok(true)` when the record matches the expected token,
/// `Ok(false)` when it does not match, and `Err` when the input is malformed.
pub fn verify_domain(domain: &str, txt_record: &str) -> Result<bool, String> {
    if domain.is_empty() {
        return Err("domain must not be empty".into());
    }
    let trimmed = txt_record.trim();
    if trimmed.is_empty() {
        return Err("txt_record must not be empty".into());
    }
    // Accept either `sentin8-verify-<hex>` or `sentin8-domain-verify=sentin8-verify-<hex>`.
    let value = trimmed
        .strip_prefix("sentin8-domain-verify=")
        .unwrap_or(trimmed)
        .trim();
    // The expected token is regenerated by the caller and passed in; this
    // function simply checks that the TXT record contains a valid-looking
    // `sentin8-verify-<32-hex>` token. The caller is responsible for comparing
    // the token against the stored `DomainBinding::verification_token`.
    if !value.starts_with("sentin8-verify-") {
        return Ok(false);
    }
    let hex_part = &value["sentin8-verify-".len()..];
    if hex_part.len() != 32 || !hex_part.chars().all(|c| c.is_ascii_hexdigit()) {
        return Ok(false);
    }
    Ok(true)
}

/// The CNAME record NAME a tenant must create for CNAME verification
/// (APP-5): `{token}.verify.{domain}` - apex domains cannot carry TXT
/// at the apex-adjacent name some DNS providers reserve, so a delegating
/// tenant proves control by pointing a CNAME at the challenge host.
pub fn cname_challenge_host(domain: &str, token: &str) -> String {
    format!("{token}.verify.{domain}")
}

/// Verify a CNAME challenge (APP-5): the caller resolves
/// `{token}.verify.{domain}` (e.g. via `dig CNAME {token}.verify.{domain}`)
/// and submits the resolved target here. Verification passes when the
/// target matches the platform's expected value
/// `cname.{instance_hostname}` - the challenge host aliasing the app
/// instance's platform hostname proves domain control (the tenant can
/// only create that record inside the zone they claim).
pub fn verify_cname(
    domain: &str,
    token: &str,
    resolved_target: &str,
    instance_hostname: &str,
) -> Result<bool, String> {
    if domain.is_empty() {
        return Err("domain must not be empty".into());
    }
    let token = token.trim();
    if !token.starts_with("sentin8-verify-") {
        return Err("token must be a `sentin8-verify-<32-hex>` challenge".into());
    }
    let hex_part = &token["sentin8-verify-".len()..];
    if hex_part.len() != 32 || !hex_part.chars().all(|c| c.is_ascii_hexdigit()) {
        return Err("token must be a `sentin8-verify-<32-hex>` challenge".into());
    }
    let resolved = resolved_target
        .trim()
        .trim_end_matches('.')
        .trim_end_matches('"');
    let expected = instance_hostname.trim().trim_end_matches('.');
    if expected.is_empty() {
        return Err("instance_hostname must not be empty".into());
    }
    Ok(resolved.eq_ignore_ascii_case(expected))
}

/// Slugify a label: lowercase, alphanumerics and hyphens only, collapse runs.
fn slugify(s: &str) -> String {
    let s = s.trim().to_lowercase();
    let mut out = String::with_capacity(s.len());
    let mut prev_dash = false;
    for ch in s.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch);
            prev_dash = false;
        } else if !prev_dash && !out.is_empty() {
            out.push('-');
            prev_dash = true;
        }
    }
    while out.ends_with('-') {
        out.pop();
    }
    out
}

// ── Tests ───────────────────────────────────────────────────────────────

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_domain_uses_pattern() {
        // Default-domain org: org_domain = {slug}.{base}.
        let d = generate_default_domain("ebank", "prod", "acme.sentin8.local");
        assert_eq!(d, "ebank.prod.acme.sentin8.local");
    }

    #[test]
    fn default_domain_slugifies_app_label() {
        let d = generate_default_domain("eBank App", "prod-env", "acme-corp.sentin8.dev");
        assert_eq!(d, "ebank-app.prod-env.acme-corp.sentin8.dev");
    }

    #[test]
    fn default_domain_supports_custom_org_domain() {
        // Custom org domain: no .{base} suffix - the app subdomain is
        // created directly under the org's entered domain.
        let d = generate_default_domain("ebank", "prod", "ibank.local");
        assert_eq!(d, "ebank.prod.ibank.local");
    }

    #[test]
    fn default_domain_strips_leading_dot_from_org_domain() {
        let d = generate_default_domain("ebank", "prod", ".ibank.local");
        assert_eq!(d, "ebank.prod.ibank.local");
    }

    #[test]
    fn txt_token_starts_with_prefix() {
        let tok = generate_dns_txt_token("ebank.prod.ibank.local");
        assert!(tok.starts_with("sentin8-verify-"));
        assert_eq!(tok.len(), "sentin8-verify-".len() + 32);
    }

    #[test]
    fn txt_token_is_unique_per_call() {
        let a = generate_dns_txt_token("acme.ebank");
        let b = generate_dns_txt_token("acme.ebank");
        assert_ne!(a, b, "random component must make tokens unique");
    }

    #[test]
    fn verify_accepts_bare_token() {
        let tok = generate_dns_txt_token("acme.ebank");
        assert!(verify_domain("acme.ebank", &tok).unwrap());
    }

    #[test]
    fn verify_accepts_prefixed_token() {
        let tok = generate_dns_txt_token("acme.ebank");
        let record = format!("sentin8-domain-verify={tok}");
        assert!(verify_domain("acme.ebank", &record).unwrap());
    }

    #[test]
    fn verify_rejects_garbage() {
        assert!(!verify_domain("acme.ebank", "not-a-token").unwrap());
        assert!(!verify_domain("acme.ebank", "sentin8-verify-nothex!!").unwrap());
    }

    #[test]
    fn verify_rejects_empty_inputs() {
        assert!(verify_domain("", "sentin8-verify-abc").is_err());
        assert!(verify_domain("acme.ebank", "").is_err());
    }

    #[test]
    fn domain_binding_struct_roundtrip() {
        let id = Uuid::new_v4();
        let b = DomainBinding {
            domain: "prod.acme.ebank.app.sentin8.local".into(),
            instance_id: id,
            verification_token: "sentin8-verify-deadbeef".into(),
            verified: false,
        };
        assert_eq!(b.instance_id, id);
        assert!(!b.verified);
    }
}
